#define rall(x) (x).rbegin(), (x).rend()
#define yes cout << "YES\n"
#define no cout << "NO\n"

void solve__()
{
    int n;
    cin >> n;
    vector<int> b(n);
    int ones = 0;
    for (int i = 0; i < n; i++)
    {
        cin >> b[i];
        if (b[i] == 1)
            ones++;
    }
    if ((n - ones) % 2 == 0)
        yes;
    else
        no;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int tc;
    cin >> tc;
    while (tc--)
    {
        solve__();
    }

    return 0;
}